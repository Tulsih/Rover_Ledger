const axios = require('axios');
require('dotenv').config();

const CLIENT_ID = process.env.MICROSOFT_CLIENT_ID;
const TENANT_ID = process.env.MICROSOFT_TENANT_ID;
const CLIENT_SECRET = process.env.MICROSOFT_CLIENT_SECRET;
const REDIRECT_URI = process.env.MICROSOFT_REDIRECT_URI || 'roverledger://auth';

/**
 * Generate Microsoft OAuth 2.0 Authorization URL
 * Used to redirect the user to Microsoft's login consent screen
 * 
 * @param {string} state - Optional state parameter for CSRF prevention
 * @param {string} customRedirectUri - Optional custom redirect URI (defaults to roverledger://auth)
 * @returns {string} Microsoft login URL
 */
const getMicrosoftAuthUrl = (state = 'rover_ledger_login', customRedirectUri = null) => {
  const rootUrl = `https://login.microsoftonline.com/${TENANT_ID}/oauth2/v2.0/authorize`;
  const options = {
    client_id: CLIENT_ID,
    response_type: 'code',
    redirect_uri: customRedirectUri || REDIRECT_URI,
    response_mode: 'query',
    scope: 'openid profile email User.Read',
    state,
  };

  const qs = new URLSearchParams(options);
  return `${rootUrl}?${qs.toString()}`;
};

/**
 * Exchange Authorization Code for Microsoft Access Token
 * Calls: POST https://login.microsoftonline.com/{tenantId}/oauth2/v2.0/token
 * 
 * @param {string} code - The authorization code received from Microsoft OAuth redirect
 * @param {string} customRedirectUri - Optional custom redirect URI used when code was requested
 * @param {string} codeVerifier - Optional PKCE code_verifier generated by the client (mobile app)
 * @returns {Promise<object>} Token response containing access_token, id_token, etc.
 */
const exchangeCodeForTokens = async (code, customRedirectUri = null, codeVerifier = null) => {
  const tokenUrl = `https://login.microsoftonline.com/${TENANT_ID}/oauth2/v2.0/token`;
  const resolvedRedirectUri = (customRedirectUri || REDIRECT_URI).trim();
  const cleanVerifier = typeof codeVerifier === 'string' ? codeVerifier.trim() : null;

  const bodyParams = new URLSearchParams({
    client_id: CLIENT_ID,
    code: code.trim(),
    redirect_uri: resolvedRedirectUri,
    grant_type: 'authorization_code',
    scope: 'openid profile email User.Read',
  });

  // Attach PKCE code_verifier if provided by client/mobile app (Public Client flow)
  // For Public Clients (mobile apps with PKCE), Azure Entra ID rejects or mishandles client_secret
  if (cleanVerifier) {
    bodyParams.append('code_verifier', cleanVerifier);
  } else if (CLIENT_SECRET) {
    // Only confidential clients (standard web server flow without PKCE) should send client_secret
    bodyParams.append('client_secret', CLIENT_SECRET);
  }

  console.log('📤 [Microsoft Token Exchange Request]:', {
    tokenUrl,
    client_id: CLIENT_ID,
    redirect_uri: resolvedRedirectUri,
    code_length: code.trim().length,
    has_code_verifier: !!cleanVerifier,
    code_verifier_length: cleanVerifier ? cleanVerifier.length : 0,
    has_client_secret: !!CLIENT_SECRET,
  });

  try {
    const response = await axios.post(tokenUrl, bodyParams.toString(), {
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded',
      },
    });

    return response.data;
  } catch (error) {
    const errorDetails = error.response ? error.response.data : error.message;
    console.error('[Microsoft Token Exchange Error]:', errorDetails);
    throw new Error(
      error.response?.data?.error_description ||
      'Failed to exchange authorization code with Microsoft'
    );
  }
};

/**
 * Fetch authenticated user's profile from Microsoft Graph API
 * Calls: GET https://graph.microsoft.com/v1.0/me
 * 
 * @param {string} accessToken - Microsoft OAuth access token
 * @returns {Promise<object>} User profile from Microsoft Graph
 */
const fetchUserProfileFromGraph = async (accessToken) => {
  const graphEndpoint = 'https://graph.microsoft.com/v1.0/me';

  try {
    const response = await axios.get(graphEndpoint, {
      headers: {
        Authorization: `Bearer ${accessToken}`,
      },
    });

    const data = response.data;

    // Microsoft returns mail or userPrincipalName for email address
    const email = data.mail || data.userPrincipalName;
    const firstName = data.givenName || '';
    const lastName = data.surname || '';
    const fullName = data.displayName || `${firstName} ${lastName}`.trim();
    const designation = data.jobTitle || null;

    return {
      microsoftId: data.id,
      email: email ? email.toLowerCase() : null,
      firstName,
      lastName,
      fullName,
      designation,
      raw: data,
    };
  } catch (error) {
    const errorDetails = error.response ? error.response.data : error.message;
    console.error('[Microsoft Graph API Error]:', errorDetails);
    throw new Error(
      error.response?.data?.error?.message ||
      'Failed to fetch user profile from Microsoft Graph API'
    );
  }
};

module.exports = {
  getMicrosoftAuthUrl,
  exchangeCodeForTokens,
  fetchUserProfileFromGraph,
};
